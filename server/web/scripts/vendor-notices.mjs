// Keep About's references tied to the exact components shipped to browsers.
import {readFile,writeFile,mkdir} from 'node:fs/promises';
const root=new URL('../',import.meta.url),check=process.argv.includes('--check');
const manifest=JSON.parse(await readFile(new URL('package.json',root)));
const components=[
  {id:'bootstrap',name:'Bootstrap',homepage:'https://getbootstrap.com/',license:'MIT',directory:'bootstrap'},
  {id:'bootstrap-icons',name:'Bootstrap Icons',homepage:'https://icons.getbootstrap.com/',license:'MIT',directory:'bootstrap-icons'},
  {id:'i18next',name:'i18next',homepage:'https://www.i18next.com/',license:'MIT',directory:'i18next'},
  {id:'date-holidays',name:'date-holidays',homepage:'https://github.com/commenthol/date-holidays',license:'ISC / CC BY-SA 3.0',directory:'date-holidays',notices:'/web/assets/date-holidays/THIRD-PARTY-LICENSES.txt'}
];
const notices=[],files=[[new URL('src/assets/notices/timekeeper-LICENSE.txt',root),await readFile(new URL('../../LICENSE',root),'utf8')]];
for(const {id,directory,...component} of components){
  const upstream=JSON.parse(await readFile(new URL(`node_modules/${id}/package.json`,root)));
  if(upstream.version!==manifest.devDependencies[id])throw new Error('Expected the pinned version of '+id);
  const license=await readFile(new URL(`src/assets/${directory}/LICENSE`,root),'utf8');
  const copyright=license.match(/^Copyright (?:\(c\)\s*)?\d[^\r\n]*/mi)?.[0];
  if(!copyright)throw new Error('Missing copyright notice for '+id);
  notices.push({...component,version:upstream.version,copyright,licenseUrl:`/web/assets/notices/${directory}-LICENSE.txt`});
  files.push([new URL(`src/assets/notices/${directory}-LICENSE.txt`,root),license]);
}
files.push([new URL('src/third-party-notices.js',root),'// Generated by scripts/vendor-notices.mjs from the pinned packages and bundled licenses.\nexport const thirdPartyNotices='+JSON.stringify(notices,null,2)+';\n']);
for(const [path,content] of files){
  if(check){if(await readFile(path,'utf8')!==content)throw new Error('Regenerate About references: '+path.pathname);}
  else{await mkdir(new URL('.',path),{recursive:true});await writeFile(path,content);}
}
console.log(`${check?'Verified':'Bundled'} About references for ${notices.length} browser components and Timekeeper's license.`);
