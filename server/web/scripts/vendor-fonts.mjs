// Bundle the guide's typefaces for offline use, preserving upstream subset CSS.
import {readFile,writeFile,mkdir} from 'node:fs/promises';
const root=new URL('../',import.meta.url),check=process.argv.includes('--check');
const manifest=JSON.parse(await readFile(new URL('package.json',root)));
const target=new URL('src/assets/fonts/',root),files=new Map();
let css='/* Generated by scripts/vendor-fonts.mjs from the pinned Fontsource packages. */\n';
for(const [id,version] of [['inter','5.3.0'],['source-serif-4','5.3.1']]) {
  const name='@fontsource-variable/'+id,source=new URL('node_modules/'+name+'/',root);
  const pkg=JSON.parse(await readFile(new URL('package.json',source)));
  if(pkg.version!==version||manifest.devDependencies[name]!==version)throw new Error('Review the pinned font version: '+name);
  files.set(id+'-LICENSE',await readFile(new URL('LICENSE',source)));
  for(const style of ['normal','italic']) {
    const upstream=await readFile(new URL(style==='normal'?'wght.css':'wght-italic.css',source),'utf8');
    const faces=upstream.match(/\/\*[^*]+\*\/\s*@font-face\s*\{[^}]+\}/g);
    for(const subset of ['latin-ext','latin']) {
      const file=`${id}-${subset}-wght-${style}.woff2`;
      const face=faces.find(value=>value.includes(`/* ${id}-${subset}-wght-${style} */`));
      if(!face||!face.includes('./files/'+file))throw new Error('Missing font subset: '+file);
      css+='\n'+face.replace('./files/','./')+'\n';
      files.set(file,await readFile(new URL('files/'+file,source)));
    }
  }
}
files.set('fonts.css',css);
for(const [name,bytes] of files) {
  const path=new URL(name,target);
  if(check) {if(!Buffer.from(await readFile(path)).equals(Buffer.from(bytes)))throw new Error('Regenerate bundled font: '+name);}
  else {await mkdir(target,{recursive:true});await writeFile(path,bytes);}
}
console.log(`${check?'Verified':'Bundled'} Inter and Source Serif 4, Latin/extended Latin, upright/italic, and OFL licenses.`);
