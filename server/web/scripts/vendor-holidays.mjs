import {readFile,writeFile,mkdir,readdir} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {data} from 'date-holidays/data';

const modules=new URL('../node_modules/',import.meta.url);
const upstream=new URL('date-holidays/',modules);
const target=new URL('../src/assets/date-holidays/',import.meta.url);
const check=process.argv.includes('--check');
const {version}=JSON.parse(await readFile(new URL('package.json',upstream)));
if(version!=='3.37.0')throw new Error('Expected date-holidays 3.37.0');
const bundle=await readFile(new URL('dist/umd.min.js',upstream));
const sourceMap=JSON.parse(await readFile(new URL('dist/umd.min.js.map',upstream)));
const components=[...new Set(sourceMap.sources.map(source=>[...source.matchAll(/node_modules\/((?:@[^/]+\/)?[^/]+)/g)].at(-1)?.[1]).filter(name=>name&&name!=='.pnpm'))].sort();
let licenses='Complete license texts for the dependencies included in the upstream browser bundle.\n';
for(const name of components) {
  const directory=new URL(name+'/',modules),files=(await readdir(directory)).filter(file=>/^(licen[cs]e|copying)(\.|$)/i.test(file)).sort();
  if(!files.length)throw new Error('Missing component license: '+name);
  for(const file of files)licenses+='\n\n'+name+' / '+file+'\n\n'+await readFile(new URL(file,directory),'utf8');
}
// Select the upstream bundle's CommonJS export without adding browser globals.
// The payload itself is unchanged; this bridge works in native modules and Node.
const engine='// Generated by scripts/vendor-holidays.mjs from date-holidays@'+version+'.\n'+
  'const module={exports:{}};const exports=module.exports;const self=globalThis;\n'+bundle.toString()+
  '\nexport default module.exports.default;\n';
const countries=Object.keys(data.holidays).sort();
const files=[
  [new URL('engine.js',target),engine],
  [new URL('countries.js',target),'// Generated by scripts/vendor-holidays.mjs.\nexport const countries='+JSON.stringify(countries)+';\n'],
  [new URL('LICENSE',target),await readFile(new URL('LICENSE',upstream))],
  [new URL('umd.min.js.LICENSE.txt',target),await readFile(new URL('dist/umd.min.js.LICENSE.txt',upstream))],
  [new URL('THIRD-PARTY-LICENSES.txt',target),licenses],
  [new URL('README.md',target),`# Public holiday data\n\nSource: [date-holidays ${version}](https://github.com/commenthol/date-holidays), pinned in the npm lockfile.\nData revision: ${data.version}; ${countries.length} countries.\n\nThe upstream browser bundle is unchanged inside a native-module bridge. It loads only when Track needs public holidays. All calendar calculations run locally.\n\nUpstream bundle SHA-256: \`${createHash('sha256').update(bundle).digest('hex')}\`.\n\nCode is ISC/MIT; holiday data is CC BY-SA 3.0 as specified in the upstream LICENSE, including its source attributions. The upstream notices and complete dependency license texts accompany the bundle.\n\nRegenerate with \`npm run vendor:holidays\`; verify with \`npm run check:assets\`.\n`]
];
for(const [path,content] of files) {
  if(check){if(!Buffer.from(await readFile(path)).equals(Buffer.from(content)))throw new Error('Regenerate holiday asset: '+path.pathname);}
  else {await mkdir(new URL('.',path),{recursive:true});await writeFile(path,content);}
}
console.log(`${check?'Verified':'Bundled'} date-holidays ${version}, data ${data.version}, ${countries.length} countries.`);
