// Bundle the pinned upstream font and generate the project catalog and API allow-list.
import {readFile, writeFile, mkdir} from 'node:fs/promises';
import {createHash} from 'node:crypto';
const source=new URL('../node_modules/@fortawesome/fontawesome-free/',import.meta.url);
const target=new URL('../src/assets/fontawesome/',import.meta.url);
const check=process.argv.includes('--check');
const {version}=JSON.parse(await readFile(new URL('package.json',source)));
if(version!=='7.3.1')throw new Error('Expected Font Awesome Free 7.3.1');
const metadata=JSON.parse(await readFile(new URL('metadata/icon-families.json',source)));
const solid=Object.fromEntries(Object.entries(metadata).filter(([,entry])=>entry.familyStylesByLicense.free.some(({family,style})=>family==='classic' && style==='solid')));
// Keep the original twelve project choices and their saved identifiers.
const favorites=['briefcase','code','globe','building','tools','flask','book','palette','chart','folder','mobile','cloud'];
const aliases={tools:'screwdriver-wrench',chart:'chart-column',mobile:'mobile-screen-button'};
const ids=[...favorites,...Object.keys(solid).filter(id=>!favorites.includes(id)).sort()];
const catalog=ids.map(id=>{
  const entry=solid[aliases[id]||id];
  return [id,aliases[id] ? id[0].toUpperCase()+id.slice(1) : entry.label,String.fromCodePoint(parseInt(entry.unicode,16)),[...entry.search.terms,...(entry.aliases?.names||[])].join(' ')];
});
const files=new Map();
const font=await readFile(new URL('webfonts/fa-solid-900.woff2',source));
files.set(new URL('fa-solid-900.woff2',target),font);
files.set(new URL('LICENSE.txt',target),await readFile(new URL('LICENSE.txt',source)));
const hash=createHash('sha256').update(font).digest('hex');
files.set(new URL('README.md',target),`# Font Awesome Free\n\nPinned source: \`@fortawesome/fontawesome-free@${version}\` from the official npm package.\n\nThe unmodified classic solid WOFF2 font is bundled for offline use under SIL OFL 1.1.\nIcon metadata is licensed under CC BY 4.0. See LICENSE.txt for upstream attribution and licenses.\nSee https://docs.fontawesome.com/web/setup/host-yourself/webfonts/ for upstream usage.\n\nWOFF2 SHA-256: \`${hash}\`.\n\nRun \`npm run vendor:icons\` to regenerate the font, project catalog and API allow-list.\n`);
files.set(new URL('../src/project-icons.js',import.meta.url),'// Generated by scripts/vendor-icons.mjs from Font Awesome Free '+version+'.\nexport const projectCatalog = [\n'+catalog.map(entry=>'  '+JSON.stringify(entry)).join(',\n')+'\n];\n');
const contractPath=new URL('../../../common/api/openapi.json',import.meta.url);
const contract=await readFile(contractPath,'utf8');
const schemaStart=contract.indexOf('"ProjectIcon": {');
const enumStart=contract.indexOf('[',contract.indexOf('"enum":',schemaStart)),enumEnd=contract.indexOf(']',enumStart);
if(schemaStart<0 || enumStart<0 || enumEnd<0)throw new Error('ProjectIcon enum not found');
const allowed=[...ids].sort();
const replacement='[\n'+allowed.map(id=>'              '+JSON.stringify(id)).join(',\n')+'\n            ]';
files.set(contractPath,contract.slice(0,enumStart)+replacement+contract.slice(enumEnd+1));
for(const [path,content] of files) {
  if(check) {
    if(!Buffer.from(await readFile(path)).equals(Buffer.from(content)))throw new Error(`Regenerate bundled icon asset: ${path.pathname}`);
  } else {
    await mkdir(new URL('.',path),{recursive:true});await writeFile(path,content);
  }
}
console.log(`${check?'Verified':'Bundled'} Font Awesome Free ${version}: ${ids.length} solid icons and local font.`);
