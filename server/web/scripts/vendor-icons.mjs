// Bundle the pinned upstream font/CSS and generate the project catalog and API allow-list.
import {readFile, writeFile, mkdir} from 'node:fs/promises';
import {createHash} from 'node:crypto';
const source=new URL('../node_modules/bootstrap-icons/',import.meta.url);
const target=new URL('../src/assets/bootstrap-icons/',import.meta.url);
const check=process.argv.includes('--check');
const {version}=JSON.parse(await readFile(new URL('package.json',source)));
if(version!=='1.13.2')throw new Error('Expected Bootstrap Icons 1.13.2');
const glyphs=JSON.parse(await readFile(new URL('font/bootstrap-icons.json',source)));
const favorites=['briefcase','code','globe','building','tools','flask','book','palette','bar-chart','folder','phone','cloud'];
const ids=[...favorites,...Object.keys(glyphs).filter(id=>!favorites.includes(id)).sort()];
const title=id=>id.split('-').map(word=>word[0].toUpperCase()+word.slice(1)).join(' ');
const keywords={'yin-yang':'balance harmony','hammer':'gavel law justice','phone':'mobile smartphone','flask':'research science experiment','bar-chart':'chart statistics report'};
const catalog=ids.map(id=>[id,title(id),keywords[id]||'']);
const files=new Map();
for(const name of ['bootstrap-icons.min.css','fonts/bootstrap-icons.woff2','fonts/bootstrap-icons.woff'])files.set(new URL(name,target),await readFile(new URL('font/'+name,source)));
files.set(new URL('LICENSE',target),await readFile(new URL('LICENSE',source)));
const hash=createHash('sha256').update(await readFile(new URL('font/fonts/bootstrap-icons.woff2',source))).digest('hex');
files.set(new URL('README.md',target),`# Bootstrap Icons\n\nPinned source: \`bootstrap-icons@${version}\` from the official npm package.\n\nThe unmodified CSS, WOFF2/WOFF fonts and MIT license are bundled for offline use.\nSee https://icons.getbootstrap.com/usage/ for upstream usage.\n\nWOFF2 SHA-256: \`${hash}\`.\n\nRun \`npm run vendor:icons\` to regenerate the assets, project catalog and API allow-list.\n`);
files.set(new URL('../src/project-icons.js',import.meta.url),'// Generated by scripts/vendor-icons.mjs from Bootstrap Icons '+version+'.\nexport const projectCatalog = [\n'+catalog.map(entry=>'  '+JSON.stringify(entry)).join(',\n')+'\n];\n');
const contractPath=new URL('../../../common/api/openapi.json',import.meta.url);
const contract=await readFile(contractPath,'utf8');
const schemaStart=contract.indexOf('"ProjectIcon": {');
const enumStart=contract.indexOf('[',contract.indexOf('"enum":',schemaStart)),enumEnd=contract.indexOf(']',enumStart);
if(schemaStart<0 || enumStart<0 || enumEnd<0)throw new Error('ProjectIcon enum not found');
const allowed=[...ids].sort();
const replacement='[\n'+allowed.map(id=>'              '+JSON.stringify(id)).join(',\n')+'\n            ]';
files.set(contractPath,contract.slice(0,enumStart)+replacement+contract.slice(enumEnd+1));
for(const [path,content] of files) {
  if(check) {
    if(!Buffer.from(await readFile(path)).equals(Buffer.from(content)))throw new Error(`Regenerate bundled icon asset: ${path.pathname}`);
  } else {
    await mkdir(new URL('.',path),{recursive:true});await writeFile(path,content);
  }
}
console.log(`${check?'Verified':'Bundled'} Bootstrap Icons ${version}: ${ids.length} icons and local fonts.`);
